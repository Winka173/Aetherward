"""Paired A/B comparison of two --batch outputs (same seeds/lineups/policies). Usage: ab_compare.py A_dir B_dir out.md title"""
import csv, math, sys
def load(d):
    rows = {}
    import gzip, os
    f = gzip.open(d + "/runs.csv.gz", "rt") if os.path.exists(d + "/runs.csv.gz") else open(d + "/runs.csv")
    for r in csv.DictReader(f):
        rows[(r["seed"], r["strategy"], r["policy"])] = r
    return rows
a, b = load(sys.argv[1]), load(sys.argv[2])
keys = sorted(set(a) & set(b))
def win(r): return r["victory"].lower() in ("1", "true")
both = sum(1 for k in keys if win(a[k]) and win(b[k])); only_a = sum(1 for k in keys if win(a[k]) and not win(b[k]))
only_b = sum(1 for k in keys if win(b[k]) and not win(a[k])); n = len(keys)
wa = sum(win(a[k]) for k in keys) / n; wb = sum(win(b[k]) for k in keys) / n
# McNemar (continuity-corrected) on discordant pairs.
chi = (abs(only_a - only_b) - 1) ** 2 / max(1, only_a + only_b)
p = math.erfc(math.sqrt(chi / 2))
wave_a = sum(int(a[k]["wave"]) for k in keys) / n; wave_b = sum(int(b[k]["wave"]) for k in keys) / n
out = [f"# {sys.argv[4]}", "", f"Paired on {n} identical (seed, lineup, policy) runs. A = `{sys.argv[1]}`, B = `{sys.argv[2]}`. Generated by `python3 Tools/Reports/ab_compare.py` (runs.csv is gzipped after comparison).", "",
       "| | A | B |", "|---|---|---|", f"| Win rate | {wa*100:.2f}% | {wb*100:.2f}% |", f"| Avg wave reached | {wave_a:.2f} | {wave_b:.2f} |", "",
       f"- Both won {both}; only A won {only_a}; only B won {only_b}.",
       f"- McNemar χ² = {chi:.1f}, p ≈ {p:.2g} ({'significant' if p < 0.05 else 'not significant'} at 0.05).", "",
       "| Policy | A win | B win |", "|---|---|---|"]
for pol in sorted({k[2] for k in keys}):
    ks = [k for k in keys if k[2] == pol]
    out.append(f"| {pol} | {sum(win(a[k]) for k in ks)/len(ks)*100:.1f}% | {sum(win(b[k]) for k in ks)/len(ks)*100:.1f}% |")
out += ["", "| Lineup | A win | B win |", "|---|---|---|"]
for st in sorted({k[1] for k in keys}):
    ks = [k for k in keys if k[1] == st]
    out.append(f"| {st} | {sum(win(a[k]) for k in ks)/len(ks)*100:.1f}% | {sum(win(b[k]) for k in ks)/len(ks)*100:.1f}% |")
out += ["", "Bots, not players: this measures the AutoPilot's outcomes, not human experience."]
open(sys.argv[3], "w").write("\n".join(out) + "\n")
print(f"A {wa*100:.2f}% B {wb*100:.2f}% onlyA {only_a} onlyB {only_b} p {p:.2g}")
