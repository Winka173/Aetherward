#!/usr/bin/env python3
"""Regenerates every Aetherward sprite/icon/UI texture deterministically.

Usage (from repo root):  python3 Tools/AssetGen/art/build_all.py
Outputs:
  Assets/_Aetherward/Resources/Art/**.png      runtime sprites (loaded via Resources.Load<Sprite>)
  Tools/AssetGen/import_settings.json          per-file pivot / PPU / 9-slice border for Tools/gen_meta.py
  Docs/Previews/*.png                          contact sheets for art review (not runtime captures)
  Docs/ASSET_MANIFEST.json                     provenance list (all procedurally generated here)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import cairo  # noqa: E402
import heroes, enemies, world, vfx, ui, icons  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
ART = os.path.join(ROOT, "Assets", "_Aetherward", "Resources", "Art")
PREVIEW = os.path.join(ROOT, "Docs", "Previews")
settings = {}
manifest = []


def content(name):
    path = os.path.join(ROOT, "Assets", "_Aetherward", "Resources", "Content", name + ".json")
    text = "\n".join(l for l in open(path).read().splitlines() if not l.strip().startswith("//"))
    return json.loads(text)


def save(cv, rel, ppu=100, pivot=(0.5, 0.5), border=(0, 0, 0, 0), max_size=2048, kind="sprite"):
    path = os.path.join(ART, rel + ".png")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    cv.save(path)
    key = os.path.relpath(path, ROOT).replace("\\", "/")
    settings[key] = {"sprite": True, "ppu": ppu, "pivot": list(pivot), "border": list(border), "filter": 1, "maxSize": max_size}
    manifest.append({"path": key, "generator": "Tools/AssetGen/art/" + kind, "license": "original, generated by project scripts"})
    return path


def sheet(paths, cols, cell, out, bg=(0.24, 0.32, 0.38)):
    rows = (len(paths) + cols - 1) // cols
    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, cols * cell, rows * cell)
    ctx = cairo.Context(surf)
    ctx.set_source_rgb(*bg)
    ctx.paint()
    for i, p in enumerate(paths):
        img = cairo.ImageSurface.create_from_png(p)
        s = cell / max(img.get_width(), img.get_height())
        ctx.save()
        ctx.translate((i % cols) * cell + (cell - img.get_width() * s) / 2, (i // cols) * cell + (cell - img.get_height() * s) / 2)
        ctx.scale(s, s)
        ctx.set_source_surface(img, 0, 0)
        ctx.paint()
        ctx.restore()
    os.makedirs(PREVIEW, exist_ok=True)
    surf.write_to_png(os.path.join(PREVIEW, out))


def main():
    hero_pivot = (0.5, (320 - 292) / 320.0)
    hero_paths = []
    for hid in heroes.HEROES:
        for pose in ("idle", "cast", "downed"):
            hero_paths.append(save(heroes.hero_sprite(hid, pose), "Heroes/%s_%s" % (hid, pose), 200, hero_pivot, kind="heroes.py"))
        for evo in ("A", "B"):
            hero_paths.append(save(heroes.hero_sprite(hid, "idle", evo), "Heroes/%s_evo%s" % (hid, evo), 200, hero_pivot, kind="heroes.py"))
            save(heroes.hero_sprite(hid, "cast", evo), "Heroes/%s_evo%s_cast" % (hid, evo), 200, hero_pivot, kind="heroes.py")
        save(heroes.portrait(hid), "Portraits/%s" % hid, 100, kind="heroes.py")
    sheet(hero_paths, 5, 200, "heroes.png")

    enemy_paths = []
    for eid in enemies.DRAWERS:
        big = eid in ("siegebreaker_golem", "rift_warden")
        pivot = (0.5, (512 - 486) / 512.0) if big else (0.5, (256 - 236) / 256.0)
        for fr in ("a", "b"):
            p = save(enemies.enemy_sprite(eid, fr), "Enemies/%s_%s" % (eid, fr), 160, pivot, kind="enemies.py")
            if fr == "a":
                enemy_paths.append(p)
    sheet(enemy_paths, 5, 220, "enemies.png", (0.30, 0.45, 0.36))

    world_paths = [save(world.background(), "World/arena_background", 80, (0.5, 0.5), max_size=4096, kind="world.py")]
    for st in ("intact", "cracked", "critical"):
        world_paths.append(save(world.crystal(st), "World/crystal_%s" % st, 160, (0.5, (400 - 372) / 400.0), kind="world.py"))
    for st in ("empty", "occupied", "highlight"):
        world_paths.append(save(world.node_pad(st), "World/node_%s" % st, 150, (0.5, 0.5), kind="world.py"))
    world_paths.append(save(world.lane_arrow(), "World/lane_arrow", 160, (0.5, 0.5), kind="world.py"))
    world_paths.append(save(world.shadow(), "World/shadow", 128, (0.5, 0.5), kind="world.py"))
    sheet(world_paths[1:], 5, 220, "world_props.png")
    from PIL import Image
    Image.open(world_paths[0]).resize((1200, 680)).save(os.path.join(PREVIEW, "arena_background.png"))

    vfx_paths = []
    for el in vfx.EL:
        vfx_paths.append(save(vfx.projectile(el), "Vfx/projectile_%s" % el, 230, kind="vfx.py"))
        vfx_paths.append(save(vfx.impact(el), "Vfx/impact_%s" % el, 192, kind="vfx.py"))
    vfx_paths.append(save(vfx.fireball(), "Vfx/fireball", 200, kind="vfx.py"))
    vfx_paths.append(save(vfx.arrow(), "Vfx/arrow", 220, kind="vfx.py"))
    for z in vfx.ZONE_COL:
        vfx_paths.append(save(vfx.zone(z), "Vfx/zone_%s" % z, 128, kind="vfx.py"))
    vfx_paths.append(save(vfx.ring(), "Vfx/ring", 128, kind="vfx.py"))
    vfx_paths.append(save(vfx.soft_glow(), "Vfx/glow", 64, kind="vfx.py"))
    vfx_paths.append(save(vfx.telegraph(), "Vfx/telegraph", 128, kind="vfx.py"))
    vfx_paths.append(save(vfx.slash(), "Vfx/slash", 160, kind="vfx.py"))
    vfx_paths.append(save(vfx.spark_particle(), "Vfx/spark", 160, kind="vfx.py"))
    vfx_paths.append(save(vfx.coin_particle(), "Vfx/coin", 160, kind="vfx.py"))
    sheet(vfx_paths, 8, 150, "vfx.png", (0.18, 0.2, 0.3))

    icon_paths = []
    for el in icons.ELEMENT_COLORS:
        icon_paths.append(save(icons.element_icon(el), "Icons/element_%s" % el, 256, kind="icons.py"))
    for sid in icons.STATUS:
        icon_paths.append(save(icons.status_icon(sid), "Icons/status_%s" % sid, 240, kind="icons.py"))
    for rid in icons.REACTIONS:
        icon_paths.append(save(icons.reaction_icon(rid), "Icons/reaction_%s" % rid, 200, kind="icons.py"))
    for role in icons.ROLES:
        icon_paths.append(save(icons.role_icon(role), "Icons/role_%s" % role, 240, kind="icons.py"))
    for name in icons.UI_ICONS:
        icon_paths.append(save(icons.ui_icon(name), "Icons/ui_%s" % name, 240, kind="icons.py"))
    sheet(icon_paths, 10, 110, "icons.png", (0.16, 0.18, 0.28))

    relic_paths = []
    for r in content("relics")["relics"]:
        relic_paths.append(save(icons.relic_icon(r["id"], r.get("family", "combat"), r.get("rarity", "common")), "Relics/%s" % r["id"], 200, kind="icons.py"))
    sheet(relic_paths, 7, 140, "relics.png", (0.16, 0.18, 0.28))
    card_paths = []
    for c in content("cards")["cards"]:
        card_paths.append(save(icons.card_icon(c["id"], c.get("type", "stat"), c.get("rarity", "common")), "Cards/%s" % c["id"], 200, kind="icons.py"))
    sheet(card_paths, 10, 120, "cards.png", (0.16, 0.18, 0.28))

    ui_paths = []
    for k in ("dark", "light", "glass", "danger"):
        ui_paths.append(save(ui.panel(k), "UI/panel_%s" % k, 100, border=(40, 40, 40, 40), kind="ui.py"))
    for kind in ("primary", "secondary", "danger", "ghost"):
        for st in ("normal", "hover", "pressed", "disabled"):
            ui_paths.append(save(ui.button(st, kind), "UI/button_%s_%s" % (kind, st), 100, border=(36, 36, 36, 36), kind="ui.py"))
    for r in ("common", "rare", "epic", "legendary", "cursed"):
        ui_paths.append(save(ui.card_frame(r), "UI/card_%s" % r, 100, border=(48, 48, 48, 80), kind="ui.py"))
    ui_paths.append(save(ui.bar("bg"), "UI/bar_bg", 100, border=(18, 18, 18, 18), kind="ui.py"))
    ui_paths.append(save(ui.bar("fill"), "UI/bar_fill", 100, border=(18, 18, 18, 18), kind="ui.py"))
    ui_paths.append(save(ui.tooltip(), "UI/tooltip", 100, border=(24, 24, 24, 24), kind="ui.py"))
    ui_paths.append(save(ui.vignette(), "UI/vignette", 100, kind="ui.py"))
    ui_paths.append(save(ui.title_logo(), "UI/title_emblem", 100, kind="ui.py"))
    sheet(ui_paths, 8, 160, "ui.png", (0.3, 0.34, 0.4))

    with open(os.path.join(ROOT, "Tools", "AssetGen", "import_settings.json"), "w") as f:
        json.dump(settings, f, indent=1, sort_keys=True)
    with open(os.path.join(ROOT, "Docs", "ASSET_MANIFEST.json"), "w") as f:
        json.dump(manifest, f, indent=1)
    print("generated %d textures" % len(settings))


if __name__ == "__main__":
    main()
