using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Aetherward.Sim.Combat;
using Aetherward.Sim.Content;
using Aetherward.Sim.Core;
using Aetherward.Sim.Run;

namespace Aetherward.Balance
{
    /// <summary>
    /// Phase 8 sample: plays one seeded run through the real simulation and writes the run breakdown the
    /// results screen is built from (Reports/RunBreakdown/run_SEED.md). Values come from the run, never invented.
    /// Usage: --breakdown SEED [--strategy name]
    /// </summary>
    public static class Breakdown
    {
        public static int Run(ContentDatabase db, string root, string[] args)
        {
            int i = Array.IndexOf(args, "--breakdown");
            ulong seed = ulong.Parse(args[i + 1], CultureInfo.InvariantCulture);
            int si = Array.IndexOf(args, "--strategy");
            Strategy st = Strategy.Find(si >= 0 ? args[si + 1] : "balanced");
            RunController rc = RunController.NewRun(db, seed, st.Starters, 0, RunUnlocks.Everything(db));
            new AutoPilot(rc, st).PlayToEnd();
            RunResults r = RunResults.Build(rc);
            RunState s = rc.State;

            var md = new StringBuilder();
            md.AppendLine("# Run breakdown — seed " + r.Seed);
            md.AppendLine();
            md.AppendLine($"Generated by `dotnet run --project Tools/SimHarness/Balance -c Release -- --breakdown {seed} --strategy {st.Name}` (AutoPilot drafting; real simulation).");
            md.AppendLine();
            md.AppendLine($"- Result: **{(r.Victory ? "Victory" : "Defeat at wave " + r.WaveReached)}** · {r.ActiveSeconds / 60f:F1} min of combat · {r.TotalReactions} reactions · {r.TotalKills} kills");
            if (!r.Victory) md.AppendLine($"- Defeat source: {r.DefeatSource}");
            md.AppendLine($"- MVP: **{r.MvpHero}** · strongest reaction: {r.StrongestReaction}");
            md.AppendLine($"- Most damaging threat to the Crystal: {r.MostDamagingThreat} ({r.MostDamagingThreatDamage:F0} damage)");
            md.AppendLine($"- Closest save: wave {r.ClosestSaveWave} with {r.ClosestSaveHpFraction * 100f:F0}% Crystal HP left");
            md.AppendLine($"- Decisive upgrade (most attributed damage): {r.DecisiveUpgrade ?? "none"} ({r.DecisiveUpgradeDamage:F0})");
            md.AppendLine($"- Hero shields absorbed {r.ShieldAbsorbed:F0} damage; deepest proc chain: generation {r.MaxProcDepth}");
            md.AppendLine();

            md.AppendLine("## Damage provenance (each hit counted once)");
            float total = r.DamageByKind.Sum();
            md.AppendLine("| Kind | Damage | Share |");
            md.AppendLine("|---|---|---|");
            foreach (DamageKind k in Enum.GetValues(typeof(DamageKind)))
            {
                float v = r.DamageByKind[(int)k];
                if (v <= 0f) continue;
                md.AppendLine($"| {k} | {v:F0} | {100f * v / Math.Max(1f, total):F1}% |");
            }
            float heroSum = r.Heroes.Sum(h => h.DamageDealt);
            md.AppendLine();
            md.AppendLine($"Consistency: provenance total {total:F0} vs per-hero total {heroSum:F0} (difference = damage with no hero source, e.g. hazards).");
            md.AppendLine();

            md.AppendLine("## Heroes");
            md.AppendLine("| Hero | Level | Evolution | Damage | Healing | Kills | Reactions | Downs |");
            md.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (HeroResult h in r.Heroes.OrderByDescending(h => h.DamageDealt))
                md.AppendLine($"| {h.HeroId} | {h.Level} | {h.EvolutionId ?? "—"} | {h.DamageDealt:F0} | {h.HealingDone:F0} | {h.Kills} | {h.Reactions} | {h.TimesDowned} |");
            md.AppendLine();
            md.AppendLine("## Top reactions");
            md.AppendLine("| Reaction | Count | Damage |");
            md.AppendLine("|---|---|---|");
            foreach (RankedEntry e in r.Reactions.Take(8)) md.AppendLine($"| {e.Id} | {e.Count} | {e.Value:F0} |");
            md.AppendLine();
            md.AppendLine("## Crystal by wave");
            md.AppendLine("| Wave | Duration (s) | Crystal damage | HP after | Kills | Leaks |");
            md.AppendLine("|---|---|---|---|---|---|");
            foreach (WaveRecord w in r.Waves) md.AppendLine($"| {w.Wave} | {w.Duration:F0} | {w.CrystalDamage:F0} | {w.CrystalHpAfter:F0} | {w.Kills} | {w.Leaks} |");
            md.AppendLine();
            md.AppendLine("## Battle Insights (logged causes, per wave that hurt the Crystal)");
            foreach (WaveRecord w in s.WaveLog)
                foreach (string code in w.Insights) md.AppendLine($"- wave {w.Wave}: `{code}` — {InsightText.Describe(new Localization(db, "en"), db, code)}");
            md.AppendLine();
            md.AppendLine("## Shareable build");
            md.AppendLine("```");
            md.AppendLine(rc.ShareCode());
            md.AppendLine("```");
            md.AppendLine("A seed replays identical conditions only on the same content version (hash in `Reports/Balance/config.json`) and with the same choices.");

            string dir = Path.Combine(root, "Reports", "RunBreakdown");
            Directory.CreateDirectory(dir);
            string path = Path.Combine(dir, "run_" + seed + ".md");
            File.WriteAllText(path, md.ToString());
            Console.WriteLine("breakdown -> " + path);
            return 0;
        }
    }
}
