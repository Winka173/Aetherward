    /// <summary>
    /// Phase 6 encounter log (--encounters [--asc N]) and headless soak (--soak WAVES).
    /// Encounters: per-wave budget table for Classic, Endless (to wave 40) and Boss Rush, with spike/dip flags.
    /// Soak: one long Endless run through the real simulation, tracking tick cost, peak entities and managed
    /// memory. Numbers are .NET headless figures only; they are not Unity FPS, GC spikes or draw calls.
    /// </summary>
    public static class Encounters
    {
        public static int Run(ContentDatabase db, string root, string[] args)
        {
            int asc = int.Parse(Arg(args, "--asc", "0"), CultureInfo.InvariantCulture);
            var md = new StringBuilder();
            md.AppendLine("# Encounter log (wave budgets)");
            md.AppendLine();
            md.AppendLine($"Generated by `dotnet run --project Tools/SimHarness/Balance -c Release -- --encounters --asc {asc}` from content data and the battle's own scaling rules.");
            md.AppendLine($"Flags compare non-boss neighbours: **spike** = effective HP ×{EncounterReport.SpikeRatio:F1} or more, **dip** = ×{EncounterReport.DipRatio:F1} or less.");
            md.AppendLine();
            int spikes = 0;
            foreach (GameMode mode in new[] { GameMode.Classic, GameMode.Endless, GameMode.BossRush })
            {
                RunController rc = RunController.NewModeRun(db, mode, 1, new[] { "ignis", "terra" }, asc, RunUnlocks.Everything(db));
                int count = mode == GameMode.Endless ? 40 : rc.TotalWaves;
                List<EncounterEntry> list = EncounterReport.ForRun(rc, count);
                spikes += list.Count(e => e.Flag == "spike");
                md.AppendLine("## " + mode);
                md.AppendLine("| Wave | Lvl | Enemies | Elite | Boss | Threat pts | Effective HP | Crystal pressure | Spawn s | /s | Mix | Affixes | Flag |");
                md.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|---|---|");
                foreach (EncounterEntry e in list)
                    md.AppendLine($"| {e.Wave} | {e.Level} | {e.Enemies} | {e.Elites} | {e.Bosses} | {e.ThreatPoints} | {e.EffectiveHp:F0} | {e.CrystalPressure:F0} | {e.Duration:F0} | {e.Density:F2} | {string.Join(" ", e.Behaviors.Select(kv => kv.Key + ":" + kv.Value))} | {string.Join(",", e.Affixes)} | {e.Flag ?? ""} |");
                md.AppendLine();
            }
            string dir = Path.Combine(root, "Reports", "Balance");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "encounters.md"), md.ToString());
            Console.WriteLine($"encounters -> {dir}/encounters.md ({spikes} spikes)");
            return 0;
        }

        public static int Soak(ContentDatabase db, string root, string[] args)
        {
            int waves = int.Parse(Arg(args, "--soak", "40"), CultureInfo.InvariantCulture);
            Strategy st = Strategy.Find("balanced");
            RunController rc = RunController.NewModeRun(db, GameMode.Endless, 777, st.Starters, 0, RunUnlocks.Everything(db));
            var pilot = new AutoPilot(rc, st);
            var rows = new StringBuilder();
            rows.AppendLine("| Wave | Ticks | ms/tick (avg) | ms/tick (max) | Peak enemies | Peak zones+projectiles | Retained MB after (post-GC) |");
            rows.AppendLine("|---|---|---|---|---|---|---|");
            long startAlloc = GC.GetTotalAllocatedBytes(true);
            int gen0 = GC.CollectionCount(0), gen2 = GC.CollectionCount(2);
            var total = Stopwatch.StartNew();
            int guard = 0;
            while (rc.State.Phase != RunPhase.Defeat && rc.State.Wave <= waves && guard++ < 100000)
            {
                if (rc.State.Phase == RunPhase.Prepare)
                {
                    pilot.Prepare();
                    Battle b = rc.StartWave();
                    if (b == null) break;
                    // Stress mode: the Crystal cannot fall, so late Endless waves (max entities) are actually reached.
                    b.Crystal.MaxHp = b.Crystal.Hp = 1e9f;
                    int ticks = 0, peakE = 0, peakFx = 0;
                    double maxMs = 0, sumMs = 0;
                    var sw = new Stopwatch();
                    while (b.Outcome == BattleOutcome.Running && ticks < 30 * 600)
                    {
                        sw.Restart();
                        b.Tick();
                        sw.Stop();
                        double ms = sw.Elapsed.TotalMilliseconds;
                        sumMs += ms;
                        if (ms > maxMs) maxMs = ms;
                        ticks++;
                        peakE = Math.Max(peakE, b.Enemies.Count);
                        peakFx = Math.Max(peakFx, b.Zones.Count + b.Projectiles.Count);
                        b.Journal.Clear();
                    }
                    int wave = rc.State.Wave;
                    rc.ResolveBattle();
                    rows.AppendLine($"| {wave} | {ticks} | {sumMs / Math.Max(1, ticks):F3} | {maxMs:F2} | {peakE} | {peakFx} | {GC.GetTotalMemory(true) / 1048576.0:F1} |");
                }
                else pilot.Step();
            }
            total.Stop();
            var md = new StringBuilder();
            md.AppendLine("# Headless soak (simulation only)");
            md.AppendLine();
            md.AppendLine("> **Not a Unity profile.** .NET 8 headless simulation on the CI/dev container; Unity FPS, rendering, GC spikes on device and draw calls were not measured (no Unity editor/player here).");
            md.AppendLine();
            md.AppendLine($"- Command: `dotnet run --project Tools/SimHarness/Balance -c Release -- --soak {waves}` · Endless, seed 777, strategy balanced, Crystal made unkillable (stress mode: reaches late waves)");
            md.AppendLine($"- Reached wave {rc.State.Wave} ({rc.State.Phase}); wall clock {total.Elapsed.TotalSeconds:F1}s; machine {Environment.ProcessorCount} threads, {System.Runtime.InteropServices.RuntimeInformation.FrameworkDescription}");
            md.AppendLine($"- Allocated during soak: {(GC.GetTotalAllocatedBytes(true) - startAlloc) / 1048576.0:F1} MB (GC counts include the forced per-wave collections used to measure retained memory: gen0 {GC.CollectionCount(0) - gen0}, gen2 {GC.CollectionCount(2) - gen2})");
            md.AppendLine("- Budget reference: one tick = 33.3 ms of game time; the simulation should stay far below ~2 ms/tick to leave room for Unity rendering on mobile.");
            md.AppendLine();
            md.Append(rows);
            string dir = Path.Combine(root, "Reports", "Performance");
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "headless_soak.md"), md.ToString());
            Console.WriteLine("soak -> " + Path.Combine(dir, "headless_soak.md"));
            return 0;
        }

        private static string Arg(string[] a, string k, string d)
        {
            int i = Array.IndexOf(a, k);
            return i >= 0 && i + 1 < a.Length ? a[i + 1] : d;
        }
    }
}
