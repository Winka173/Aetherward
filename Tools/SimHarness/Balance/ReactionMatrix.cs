using System.IO;
using System.Text;
using Aetherward.Sim.Content;

namespace Aetherward.Balance
{
    /// <summary>Writes Docs/Expansion/ELEMENT_REACTION_MATRIX.md (all 66 pairs) from live content.</summary>
    public static class ReactionMatrix
    {
        private static string Esc(string s) => (s ?? "").Replace("|", "\\|").Replace("\n", "<br>");

        public static void Write(ContentDatabase db, string path)
        {
            var l = new Localization(db, "en");
            var vi = new Localization(db, "vi");
            Element[] all = ElementUtil.All;
            var sb = new StringBuilder();
            sb.AppendLine("# Element Reaction Matrix (12 × 12)");
            sb.AppendLine();
            sb.AppendLine("Generated by `dotnet run --project Tools/SimHarness/Balance -- --catalog` from `elements.json` + `reactions.json`. Do not edit by hand.");
            sb.AppendLine();
            sb.AppendLine("Legend: **S** = Signature (authored), **G** = Generic (named template), **g** = Generic (auto “A·B Burst”), **N** = Neutral (auras coexist), **B** = Blocked by design. Launch reactions keep their original rules (L).");
            sb.AppendLine();
            sb.Append("| |");
            foreach (Element e in all) sb.Append(' ').Append(l.Element(e)).Append(" |");
            sb.AppendLine();
            sb.Append("|---|");
            foreach (Element _ in all) sb.Append("---|");
            sb.AppendLine();
            int sig = 0, gen = 0, auto = 0, neu = 0, blk = 0;
            for (int i = 0; i < all.Length; i++)
            {
                sb.Append("| **").Append(l.Element(all[i])).Append("** |");
                for (int j = 0; j < all.Length; j++)
                {
                    if (i == j) { sb.Append(" — |"); continue; }
                    ReactionDef r = db.ReactionFor(all[i], all[j]);
                    ReactionCategory c = db.CategoryFor(all[i], all[j]);
                    string cell;
                    if (r == null) cell = c == ReactionCategory.Neutral ? "N" : "B";
                    else if (r.AutoNamed) cell = "g";
                    else cell = (c == ReactionCategory.Signature ? "S" : "G") + (r.Legacy ? "L" : "") + " " + l.ReactionName(r.Id);
                    sb.Append(' ').Append(cell).Append(" |");
                    if (j > i)
                    {
                        if (r == null) { if (c == ReactionCategory.Neutral) neu++; else blk++; }
                        else if (r.AutoNamed) auto++;
                        else if (c == ReactionCategory.Signature) sig++;
                        else gen++;
                    }
                }
                sb.AppendLine();
            }
            sb.AppendLine();
            sb.AppendLine($"**Totals (66 unordered pairs):** Signature {sig} · Generic named {gen} · Generic auto {auto} · Neutral {neu} · Blocked {blk}.");
            sb.AppendLine();
            sb.AppendLine("## Statuses per element");
            sb.AppendLine("| Element | Stage | Status | Rule |");
            sb.AppendLine("|---|---|---|---|");
            foreach (Element e in all)
            {
                ElementDef d = db.ElementDef(e);
                sb.AppendLine($"| {l.Element(e)} / {vi.Element(e)} | {d.Stage} | {l.Get("status." + d.StatusKey)} | {Esc(l.Get("status." + d.StatusKey + ".desc"))} |");
            }
            sb.AppendLine();
            sb.AppendLine("## Authored and named interactions");
            sb.AppendLine("| ID | Pair | Category | Cooldown / target | Rules (tooltip) |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (ReactionDef r in db.Reactions.Values)
            {
                if (r.AutoNamed) continue;
                string cat = r.Category + (r.Legacy ? " (launch)" : "") + (r.Params.Get("worldCooldown") > 0 ? $", once per {r.Params.Get("worldCooldown")}s" : "");
                sb.AppendLine($"| `{r.Id}` | {l.Element(r.A)} + {l.Element(r.B)} | {cat} | {r.Cooldown}s | **{l.ReactionName(r.Id)}**: {Esc(ContentValidator.ReactionText(l, r))} |");
            }
            sb.AppendLine();
            sb.AppendLine("## Neutral / blocked pairs");
            sb.AppendLine("| Pair | Category | Reason |");
            sb.AppendLine("|---|---|---|");
            for (int i = 0; i < all.Length; i++)
                for (int j = i + 1; j < all.Length; j++)
                {
                    int p = ElementUtil.PairIndex(all[i], all[j]);
                    if (db.PairNote.TryGetValue(p, out string note))
                        sb.AppendLine($"| {l.Element(all[i])} + {l.Element(all[j])} | {db.PairCategory[p]} | {Esc(l.Get("pair." + note))} |");
                }
            sb.AppendLine();
            sb.AppendLine("## Caps (all reactions)");
            sb.AppendLine("- Proc generation cap 2 (secondary applications carry generation+1; generation ≥ 2 cannot react).");
            sb.AppendLine("- Per target: 6 reactions per second and a per-pair cooldown; world: 48 reactions per tick; team-buff reactions also have a battle-wide cooldown.");
            sb.AppendLine("- Fields: per-id concurrent cap (`maxCount`), oldest expires first. Doom ≤ 5 stacks, Poison ≤ 10, contagion depth ≤ 2, Unstable collapse cooldown 2s, Root immunity 1.5s, bosses never rooted/pulled/executed.");
            sb.AppendLine("- Tests: `ElementExpansionTests` (coverage, statuses, every reaction resolves within caps, random 12-element storm), `ReactionTests` (launch regression).");
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, sb.ToString());
        }
    }
}
