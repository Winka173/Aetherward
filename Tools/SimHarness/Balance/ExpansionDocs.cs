using System.Collections.Generic;
using System.IO;
using System.Text;
using Aetherward.Sim.Content;
using Aetherward.Sim.Meta;

namespace Aetherward.Balance
{
    /// <summary>Generates Docs/Expansion/HERO_ROSTER.md and CONTENT_MATRIX.csv from live content.</summary>
    public static class ExpansionDocs
    {
        private static readonly HashSet<string> LaunchHeroes = new HashSet<string>
        { "ignis", "cinder", "marina", "tidal", "volt", "raiden", "freya", "glacius", "zephyr", "sylph", "terra", "magnus" };

        private static string Esc(string s) => (s ?? "").Replace("|", "\\|").Replace("\n", "<br>");

        public static void Write(ContentDatabase db, string root)
        {
            var l = new Localization(db, "en");
            var fx = new EffectDescriber(db, l);
            string dir = Path.Combine(root, "Docs", "Expansion");
            Directory.CreateDirectory(dir);

            var sb = new StringBuilder();
            sb.AppendLine("# Hero Roster");
            sb.AppendLine();
            sb.AppendLine("Generated by `dotnet run --project Tools/SimHarness/Balance -- --catalog`. Texts come from the in-game tooltip generator, so numbers match the simulation.");
            sb.AppendLine($"Implemented heroes: **{db.HeroList.Count}** / 36 target. Each has 2 evolution branches that change mechanics (validated). Behaviour test: `EveryHeroSkillCastsInARealWave`, `EveryEvolutionBuildsAndCasts`.");
            sb.AppendLine();
            sb.AppendLine("| ID | Name / Title | Element · Role | Skill | Passive | Evolutions (mechanical change) | Unlock | Wave |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (HeroDef h in db.HeroList)
            {
                var evos = new List<string>();
                foreach (string id in h.Evolutions)
                {
                    EvolutionDef e = db.Evolutions[id];
                    evos.Add("**" + l.Get(e.NameKey) + "**: " + l.Get(e.DescKey));
                }
                string unlock = h.StarterUnlocked ? "starter" : "—";
                foreach (UnlockRule r in MetaProfile.Rules)
                    if (r.Id == "hero:" + h.Id) unlock = r.Condition + " " + (r.Param ?? r.Value.ToString());
                sb.AppendLine($"| `{h.Id}` | {l.Get(h.NameKey)} — {l.Get(h.TitleKey)} | {l.Element(h.Element)} · {l.Role(h.Role)}{(h.Melee ? " (melee)" : "")} | **{l.Get(h.Skill.NameKey)}**: {Esc(l.SkillText(h.Skill, h.Skill.DescKey))} | **{l.Get(h.PassiveNameKey)}**: {Esc(l.PassiveText(h.PassiveParams, h.PassiveDescKey))} | {Esc(string.Join("<br>", evos))} | {unlock} | {(LaunchHeroes.Contains(h.Id) ? "launch" : "expansion")} |");
            }
            sb.AppendLine();
            sb.AppendLine("## Traits");
            sb.AppendLine("| ID | Rarity | Eligibility | Rule |");
            sb.AppendLine("|---|---|---|---|");
            foreach (TraitDef t in db.TraitList)
            {
                string elig = (t.RequireElement != Element.None ? l.Element(t.RequireElement) + " " : "") + (t.RequireRoles.Count > 0 ? string.Join("/", t.RequireRoles.ConvertAll(r => l.Role(r))) : "");
                if (elig.Length == 0) elig = "any";
                List<string> lines = fx.Describe(t.Effects);
                sb.AppendLine($"| `{t.Id}` | {t.Rarity} | {elig} | **{l.Get(t.NameKey)}**: {Esc(l.PassiveText(t.Behaviour, t.DescKey))}{(lines.Count > 0 ? " (" + string.Join(", ", lines) + ")" : "")} |");
            }
            File.WriteAllText(Path.Combine(dir, "HERO_ROSTER.md"), sb.ToString());

            var csv = new StringBuilder("id,category,phase,element_or_family,rarity,asset,status,evidence\n");
            foreach (HeroDef h in db.HeroList)
                csv.AppendLine($"{h.Id},hero,{(LaunchHeroes.Contains(h.Id) ? "mvp" : "expansion")},{ElementUtil.Key(h.Element)},,Heroes/{h.Id}_*,IMPLEMENTED_UNVERIFIED (sim VERIFIED),EveryHeroSkillCastsInARealWave");
            foreach (EvolutionDef e in db.Evolutions.Values)
                csv.AppendLine($"{e.Id},evolution,{(LaunchHeroes.Contains(e.HeroId) ? "mvp" : "expansion")},{e.HeroId},,Heroes/{e.HeroId}_evoA/B,IMPLEMENTED_UNVERIFIED (sim VERIFIED),EveryEvolutionBuildsAndCasts");
            foreach (ReactionDef r in db.Reactions.Values)
                csv.AppendLine($"{r.Id},reaction-{r.Category.ToString().ToLowerInvariant()},{(r.Legacy ? "mvp" : "expansion")},{ElementUtil.Key(r.A)}+{ElementUtil.Key(r.B)},,{(r.AutoNamed ? "Icons/reaction_generic" : "Icons/reaction_" + r.Id)},IMPLEMENTED_UNVERIFIED (sim VERIFIED),EveryReactionResolvesWithinCaps");
            foreach (EnemyDef e in db.Enemies.Values)
                csv.AppendLine($"{e.Id},{(e.Boss ? "boss" : e.Elite ? "elite" : "enemy")},,{string.Join("/", e.Tags)},,Enemies/{e.Id}_a/b,IMPLEMENTED_UNVERIFIED (sim VERIFIED),ContentPassesValidation");
            foreach (RelicDef r in db.RelicList)
                csv.AppendLine($"{r.Id},{(r.Fusion ? "relic-fusion" : r.Tags.Contains("keystone") ? "relic-keystone" : "relic")},,{r.Family.ToString().ToLowerInvariant()},{r.Rarity.ToString().ToLowerInvariant()},Relics/{r.Id},IMPLEMENTED_UNVERIFIED (sim VERIFIED),ContentPassesValidation");
            foreach (CardDef c in db.CardList)
                csv.AppendLine($"{c.Id},card-{EnumParse.ToSnake(c.Type.ToString())},,,{c.Rarity.ToString().ToLowerInvariant()},Cards/{c.Id},IMPLEMENTED_UNVERIFIED (sim VERIFIED),ContentPassesValidation");
            foreach (TraitDef t in db.TraitList)
                csv.AppendLine($"{t.Id},trait,expansion,,{t.Rarity.ToString().ToLowerInvariant()},Icons/trait_{t.Id},IMPLEMENTED_UNVERIFIED (sim VERIFIED),TraitTests");
            File.WriteAllText(Path.Combine(dir, "CONTENT_MATRIX.csv"), csv.ToString());
        }
    }
}
