using System.Collections.Generic;
using System.IO;
using System.Text;
using Aetherward.Sim.Content;

namespace Aetherward.Balance
{
    /// <summary>Writes Docs/CONTENT_CATALOG.md from live content using the in-game tooltip generator.</summary>
    public static class Catalog
    {
        private static string Esc(string s) => (s ?? "").Replace("|", "\\|").Replace("\n", "<br>");

        public static void Write(ContentDatabase db, string path)
        {
            var l = new Localization(db, "en");
            var fx = new EffectDescriber(db, l);
            var sb = new StringBuilder();
            sb.AppendLine("# Content Catalog");
            sb.AppendLine();
            sb.AppendLine("Generated by `dotnet run --project Tools/SimHarness/Balance -- --catalog` from `Assets/_Aetherward/Resources/Content/*.json`.");
            sb.AppendLine("Mechanics columns are produced by the same `Localization`/`EffectDescriber` code the game uses for tooltips, so they match the simulation numbers.");
            sb.AppendLine("Every entry is wired into the simulation (no stub effects); validation: `ContentValidationTests`, behaviour: tests listed per section. Art = sprite under `Resources/Art`.");
            sb.AppendLine();
            sb.AppendLine("## Heroes (12)");
            sb.AppendLine("| ID | Name | Element / Role | Skill (from data) | Passive | Evolutions | Art | State |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (HeroDef h in db.HeroList)
            {
                var evos = new List<string>();
                foreach (string e in h.Evolutions) evos.Add(l.Get("evo." + e + ".name") + " (`" + e + "`)");
                sb.AppendLine($"| `{h.Id}` | {l.Get(h.NameKey)} | {l.Element(h.Element)} / {l.Role(h.Role)} | **{l.Get(h.Skill.NameKey)}**: {Esc(l.SkillText(h.Skill, h.Skill.DescKey))} | **{l.Get(h.PassiveNameKey)}**: {Esc(l.PassiveText(h.PassiveParams, h.PassiveDescKey))} | {string.Join("<br>", evos)} | `Heroes/{h.Id}_idle/_cast/_downed/_evoA/_evoB`, `Portraits/{h.Id}` | Implemented, tested (`EveryHeroSkillCastsInARealWave`) |");
            }
            sb.AppendLine();
            sb.AppendLine("## Evolution branches (24)");
            sb.AppendLine("| ID | Hero | Branch | Mechanical change | Extra stats | State |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (HeroDef h in db.HeroList)
                foreach (string id in h.Evolutions)
                {
                    EvolutionDef e = db.Evolutions[id];
                    SkillDef s = h.Skill.With(e.Skill);
                    string extra = string.Join("<br>", fx.Describe(e.Effects));
                    if (e.RoleOverride.HasValue) extra += (extra.Length > 0 ? "<br>" : "") + "Role → " + l.Role(e.RoleOverride.Value);
                    if (e.TargetingOverride.HasValue) extra += (extra.Length > 0 ? "<br>" : "") + "Targeting → " + e.TargetingOverride.Value;
                    sb.AppendLine($"| `{id}` | {l.Get(h.NameKey)} | {l.Get(e.NameKey)} | **{l.Get(s.NameKey)}** (`{s.Kind}`): {Esc(l.SkillText(s, s.DescKey))} | {Esc(extra)} | Implemented, tested (`EveryEvolutionBuildsAndCasts`) |");
                }
            sb.AppendLine();
            sb.AppendLine("## Reactions (15)");
            sb.AppendLine("| ID | Pair | Effect | Base / Attack scale | Per-target cooldown | Icon | State |");
            sb.AppendLine("|---|---|---|---|---|---|---|");
            foreach (ReactionDef r in db.Reactions.Values)
                sb.AppendLine($"| `{r.Id}` | {l.Element(r.A)} + {l.Element(r.B)} | {Esc(ContentValidator.ReactionText(l, r))} | {r.BaseDamage} / {r.AttackScale} | {r.Cooldown}s | `Icons/reaction_{r.Id}` | Implemented (`ReactionTests`) |");
            sb.AppendLine();
            sb.AppendLine("## Enemies and bosses");
            sb.AppendLine("| ID | Name | Behaviour | HP / ATK / DEF / Speed (wave 1) | Counterplay | Art | State |");
            sb.AppendLine("|---|---|---|---|---|---|---|");
            foreach (EnemyDef e in db.Enemies.Values)
                sb.AppendLine($"| `{e.Id}` | {l.Get(e.NameKey)} | {e.Behavior}{(e.Boss ? " (boss)" : e.Elite ? " (elite)" : "")} | {e.Hp} / {e.Attack} / {e.Defense} / {e.Speed} | {Esc(l.Get(e.DescKey))} | `Enemies/{e.Id}_a/_b` | Implemented |");
            sb.AppendLine();
            sb.AppendLine("## Relics (25 + 3 fusions)");
            sb.AppendLine("| ID | Name | Family / Rarity | Effect (generated) | Icon | State |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (RelicDef r in db.RelicList)
                sb.AppendLine($"| `{r.Id}` | {l.Get(r.NameKey)}{(r.Fusion ? " *(fusion)*" : "")} | {r.Family} / {l.Rarity(r.Rarity)} | {Esc(string.Join("\n", fx.Describe(r.Effects)))} | `Relics/{r.Id}` | Implemented{(r.Id == "phoenix_feather" ? " (`PhoenixFeatherRevivesOncePerWave`)" : r.Id == "elemental_mirror" ? " (`ElementalMirrorStaysBoundedInDenseCrowds`)" : "")} |");
            sb.AppendLine();
            sb.AppendLine("Fusions: " + string.Join(", ", db.Fusions.ConvertAll(f => $"`{f.A}` + `{f.B}` → `{f.Result}`")) + " (`FusionReplacesBothComponents`).");
            sb.AppendLine();
            sb.AppendLine($"## Upgrade / mutation / pact cards ({db.CardList.Count})");
            sb.AppendLine("| ID | Name | Type / Rarity | Requires | Effect (generated) | Drawback | Max stacks | State |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (CardDef c in db.CardList)
            {
                var req = new List<string>();
                if (c.Requires.Element != Element.None) req.Add(l.Element(c.Requires.Element));
                if (c.Requires.Role.HasValue) req.Add(l.Role(c.Requires.Role.Value));
                if (!string.IsNullOrEmpty(c.Requires.Hero)) req.Add(l.Get("hero." + c.Requires.Hero + ".name") + " Lv" + c.Requires.MinLevel);
                sb.AppendLine($"| `{c.Id}` | {l.Get(c.NameKey)} | {c.Type} / {l.Rarity(c.Rarity)} | {string.Join(", ", req)} | {Esc(string.Join("\n", fx.Describe(c.Effects)))} | {Esc(c.DrawbackKey != null ? l.Get(c.DrawbackKey) : "")} | {c.MaxStacks} | Implemented |");
            }
            sb.AppendLine();
            sb.AppendLine("## Waves (20)");
            sb.AppendLine("| Wave | Name | Enemies | Lanes | Rewards | Gold / Essence | Time limit | Hint |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            foreach (WaveDef w in db.Waves)
            {
                var enemies = new List<string>();
                foreach (SpawnGroup g in w.Groups) enemies.Add(g.Count + "× " + g.Enemy + (g.Affix != null ? " (" + g.Affix + ")" : ""));
                var lanes = new List<string>();
                foreach (int ln in Aetherward.Sim.Combat.Battle.LanesForWave(w)) lanes.Add(db.Arena.Lanes[ln].Id);
                sb.AppendLine($"| {w.Number} | {l.Get(w.NameKey)} | {string.Join(", ", enemies)} | {string.Join(", ", lanes)} | {string.Join(", ", w.Rewards)} | {w.Gold} / {w.Essence} | {w.TimeLimit}s | {Esc(l.Get(w.HintKey))} |");
            }
            sb.AppendLine();
            sb.AppendLine("## Events");
            foreach (EventDef e in db.Events.Values)
            {
                sb.AppendLine($"- `{e.Id}` **{l.Get(e.NameKey)}**: " + string.Join(" / ", e.Options.ConvertAll(o => l.Get(o.TextKey) + (o.DrawbackKey != null ? " (" + l.Get(o.DrawbackKey) + ")" : ""))));
            }
            sb.AppendLine();
            sb.AppendLine("## Arena");
            sb.AppendLine($"Arcane Sanctuary: 1 crystal, {db.Arena.Nodes.Count} defence nodes, {db.Arena.Lanes.Count} lanes ({string.Join(", ", db.Arena.Lanes.ConvertAll(x => x.Id))}). Background art is generated from the same lane polylines (`World/arena_background`).");
            File.WriteAllText(path, sb.ToString());
            System.Console.WriteLine("catalog -> " + path);
        }
    }
}
