#!/usr/bin/env python3
"""Aetherward art pipeline CLI (reproducible, transactional).

  generate  [--stage DIR]                 build every 2D sprite (Tools/AssetGen/art) into a staging dir
  render    [--stage DIR] [--only NAME]   Blender 4.x headless renders (Tools/ArtPipeline/blender/*.py) into staging
  validate  [--stage DIR | --live]        Art Quality Validator on staging or the live project
  preview   [--stage DIR] [--assets GLOB] contact sheets at on-screen size, battlefields, spell density, CVD
  pack                                    sprite-atlas plan + texture-memory estimate (live project)
  diff      [--stage DIR]                 changed/added/removed vs live, pixel deltas, before/after sheets
  import    [--stage DIR] [--allow-warnings-only]   validated, backed-up, all-or-nothing copy of CHANGED files
  rollback  [--journal FILE]              restore the files replaced by the last (or given) import
  lock                                    write Tools/ArtPipeline/manifest.lock.json (hashes of live outputs)

Staging defaults to Temp/ArtStage (git-ignored). Imports never touch hand-authored files: only paths listed in
the generator manifest are written, every replaced file is backed up first (Temp/ArtBackups/<stamp>/), and the
journal makes the import reversible. Run from the repository root.
"""
import argparse
import datetime
