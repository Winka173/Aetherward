import glob
import json
import os
import shutil
import subprocess
import sys

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import artlib as A  # noqa: E402
import validate as V  # noqa: E402

PIPELINE_VERSION = "1.0"
DEFAULT_STAGE = os.path.join(A.ROOT, "Temp", "ArtStage")
BACKUPS = os.path.join(A.ROOT, "Temp", "ArtBackups")
LOCK = os.path.join(A.HERE, "manifest.lock.json")
LIVE_REL = "Assets/_Aetherward/Resources/Art"
BLENDER_DIR = os.path.join(A.HERE, "blender")
REPORTS = os.path.join(A.ROOT, "Reports", "ArtQuality")


def log(msg):
    print("[ap] " + msg, flush=True)


def stage_paths(stage):
    return {"art": os.path.join(stage, "Art"), "settings": os.path.join(stage, "import_settings.json"),
            "manifest": os.path.join(stage, "manifest.json"), "preview": os.path.join(stage, "Previews")}


def files_under(d):
    out = []
    for dp, _, fs in os.walk(d):
        for f in fs:
            if f.endswith(".png"):
                out.append(os.path.relpath(os.path.join(dp, f), d).replace("\\", "/"))
    return sorted(out)


# ---------------------------------------------------------------------------- generate / render

def cmd_generate(a):
    sp = stage_paths(a.stage)
    if os.path.exists(sp["art"]):
        shutil.rmtree(sp["art"])
    os.makedirs(sp["art"], exist_ok=True)
    env = dict(os.environ, AW_ART_OUT=sp["art"], AW_PREVIEW_OUT=sp["preview"], AW_SETTINGS_OUT=sp["settings"], AW_MANIFEST_OUT=sp["manifest"])
    r = subprocess.run([sys.executable, os.path.join(A.ROOT, "Tools", "AssetGen", "art", "build_all.py")], env=env,
                       capture_output=True, text=True)
    if r.returncode:
        log("generate FAILED:\n" + r.stdout[-2000:] + r.stderr[-4000:])
        return 2
    log(r.stdout.strip().splitlines()[-1] if r.stdout.strip() else "generated")
    if a.with_blender:
        return cmd_render(a)
    return 0


def blender_bin():
    return shutil.which("blender")


def cmd_render(a):
    exe = blender_bin()
    if not exe:
        log("render BLOCKED: blender not found on PATH")
        return 3
    sp = stage_paths(a.stage)
    scripts = sorted(glob.glob(os.path.join(BLENDER_DIR, "*.py")))
    scripts = [s for s in scripts if not os.path.basename(s).startswith("_") and (not a.only or a.only in os.path.basename(s))]
    settings = A.load_json(sp["settings"]) if os.path.exists(sp["settings"]) else {}
    manifest = A.load_json(sp["manifest"]) if os.path.exists(sp["manifest"]) else []
    for s in scripts:
        log("blender " + os.path.basename(s))
        r = subprocess.run([exe, "--background", "--factory-startup", "--python", s, "--", sp["art"]],
                           capture_output=True, text=True, timeout=1800)
        out = [l for l in r.stdout.splitlines() if l.startswith("AW_OUTPUT ")]
        if r.returncode or not out:
            log("render FAILED " + os.path.basename(s) + ":\n" + r.stdout[-3000:] + r.stderr[-3000:])
            return 2
        for line in out:
            rec = json.loads(line[len("AW_OUTPUT "):])
            key = LIVE_REL + "/" + rec["rel"]
            settings[key] = rec["settings"]
            manifest = [m for m in manifest if m["path"] != key]
            manifest.append({"path": key, "generator": "Tools/ArtPipeline/blender/" + os.path.basename(s),
                             "license": "original, generated by project scripts (Blender " + rec.get("blender", "?") + ")"})
    A.dump_json(settings, sp["settings"], indent=1, sort_keys=True)
    A.dump_json(manifest, sp["manifest"], indent=1)
    return 0


# ---------------------------------------------------------------------------- validate

def validate_dir(art, settings, manifest, out):
    args = V.parser().parse_args(["--art", art, "--settings", settings, "--manifest", manifest, "--out", out])
    rep = V.run(args)
    return rep, V.write(rep, out)


def cmd_validate(a):
    if a.live:
        rep, n = validate_dir(A.ART, A.SETTINGS, A.MANIFEST, REPORTS)
    else:
        sp = stage_paths(a.stage)
        # Staged manifest paths name live locations: validate against a manifest rewritten to the staging root.
        man = A.load_json(sp["manifest"])
        stage_rel = os.path.relpath(sp["art"], A.ROOT).replace("\\", "/")
        for m in man:
            m["path"] = m["path"].replace(LIVE_REL, stage_rel, 1)
        sett = {k.replace(LIVE_REL, stage_rel, 1): v for k, v in A.load_json(sp["settings"]).items()}
        A.dump_json(man, sp["manifest"] + ".staged.json")
        A.dump_json(sett, sp["settings"] + ".staged.json")
        ensure_stage_metas(sp["art"])
        rep, n = validate_dir(sp["art"], sp["settings"] + ".staged.json", sp["manifest"] + ".staged.json", os.path.join(a.stage, "report"))
    log(f"validate: {len(rep.assets)} assets, {n} blocking")
    return 1 if n else 0


def ensure_stage_metas(art):
    """Staged PNGs reuse the live .meta (same GUID) so the validator checks the GUIDs that will ship."""
    for r in files_under(art):
        live = os.path.join(A.ART, r + ".meta")
        dst = os.path.join(art, r + ".meta")
        if os.path.exists(live) and not os.path.exists(dst):
            shutil.copyfile(live, dst)
        elif not os.path.exists(dst):
            A.write_text(dst, "fileFormatVersion: 2\nguid: %s\n" % A.sha256_text("stage:" + r)[:32])


# ---------------------------------------------------------------------------- preview

def px_per_unit(spec, height):
    return height / spec["screen"]["worldUnitsTall"]


def on_screen(img, ppu_asset, target_ppu):
    s = target_ppu / ppu_asset
    w, h = max(1, round(img.width * s)), max(1, round(img.height * s))
    return img.resize((w, h), Image.LANCZOS)


def battlefield_tiles(size):
    tiles = []
    for p in sorted(glob.glob(os.path.join(A.ART, "World", "bg_*.png"))) + [os.path.join(A.ART, "World", "arena_background.png")]:
        if os.path.exists(p):
            im = Image.open(p).convert("RGBA")
            w, h = im.size
            tiles.append((os.path.basename(p)[:-4], im.crop((w // 2 - w // 8, h // 2 - h // 8, w // 2 + w // 8, h // 2 + h // 8)).resize(size)))
    return tiles


def spell_overlay(size):
    acc = Image.new("RGBA", size, (0, 0, 0, 0))
    for p in sorted(glob.glob(os.path.join(A.ART, "Vfx", "field_*.png")))[::7][:5]:
        acc.alpha_composite(Image.open(p).convert("RGBA").resize(size))
    return acc


def contact_sheet(assets, art, settings_key, out_path, title, spec):
    """Rows = assets; columns = 720p and 1080p on-screen size over darkest/brightest battlefield, dense spells, CVD."""
    sett = A.load_json(settings_key) if os.path.exists(settings_key) else {}
    ppu720 = px_per_unit(spec, spec["screen"]["referenceHeights"]["phone_small_720p"])
    ppu1080 = px_per_unit(spec, spec["screen"]["referenceHeights"]["phone_1080p"])
    cell = 150
    tiles = battlefield_tiles((cell, cell))
    lum = sorted(tiles, key=lambda t: float(np.asarray(t[1].convert("L")).mean()))
    picks = [lum[0], lum[-1]] if lum else []
    spells = spell_overlay((cell, cell))
    cols = ["720p", "1080p dark", "1080p light", "1080p spells", "deutan", "protan", "tritan"]
    sheet = Image.new("RGBA", (220 + cell * len(cols), 40 + cell * len(assets)), (24, 26, 36, 255))
    d = ImageDraw.Draw(sheet)
    d.text((8, 8), title, fill=(240, 240, 240))
    for j, c in enumerate(cols):
        d.text((220 + j * cell + 4, 24), c, fill=(200, 200, 210))
    for i, rel in enumerate(assets):
        p = os.path.join(art, rel)
        if not os.path.exists(p):
            continue
        im = Image.open(p).convert("RGBA")
        key = LIVE_REL + "/" + rel
        ppu = sett.get(key, {}).get("ppu", 100)
        y = 40 + i * cell
        d.text((8, y + cell // 2 - 6), rel[:34], fill=(220, 220, 220))
        small = on_screen(im, ppu, ppu720)
        big = on_screen(im, ppu, ppu1080)
        bgs = [Image.new("RGBA", (cell, cell), (60, 64, 80, 255))] + [t[1] for t in picks] + [picks[0][1].copy() if picks else Image.new("RGBA", (cell, cell), (0, 0, 0, 255))]
        sprites = [small, big, big, big]
        for j, (bg, sp) in enumerate(zip(bgs, sprites)):
            tile = bg.copy()
            if j == 3:
                tile.alpha_composite(spells)
            tile.alpha_composite(sp, ((cell - sp.width) // 2, max(0, cell - sp.height - 6)))
            sheet.alpha_composite(tile, (220 + j * cell, y))
        base = bgs[1].copy() if len(bgs) > 1 else bgs[0].copy()
        base.alpha_composite(big, ((cell - big.width) // 2, max(0, cell - big.height - 6)))
        rgb = np.asarray(base.convert("RGB"), dtype=np.float64) / 255.0
        for k, kind in enumerate(("deuteranopia", "protanopia", "tritanopia")):
            sim = (A.simulate_cvd(rgb, kind) * 255).clip(0, 255).astype(np.uint8)
            sheet.alpha_composite(Image.fromarray(sim, "RGB").convert("RGBA"), (220 + (4 + k) * cell, y))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    sheet.convert("RGB").save(out_path)
    return out_path


def cmd_preview(a):
    spec = A.load_json(A.SPEC)
    art = stage_paths(a.stage)["art"] if a.stage_preview else A.ART
    sett = stage_paths(a.stage)["settings"] if a.stage_preview else A.SETTINGS
    rels = [r for r in files_under(art) if fnmatch.fnmatch(r, a.assets)]
    if not rels:
        log("preview: no assets match " + a.assets)
        return 1
    out = a.out or os.path.join(REPORTS, "previews")
    for i in range(0, len(rels), 24):
        chunk = rels[i:i + 24]
        p = contact_sheet(chunk, art, sett, os.path.join(out, f"sheet_{a.name}_{i // 24:02d}.png"), f"{a.assets} ({i + 1}-{i + len(chunk)}) on-screen", spec)
        log("preview -> " + os.path.relpath(p, A.ROOT))
    return 0


# ---------------------------------------------------------------------------- pack (atlas plan)

def shelf_pack(sizes, page, pad):
    """Simple deterministic shelf packing; returns number of pages used."""
    pages, x, y, row = 1, 0, 0, 0
    for w, h in sorted(sizes, key=lambda s: (-s[1], -s[0])):
        w, h = w + pad * 2, h + pad * 2
        if w > page or h > page:
            pages += 1
            continue
        if x + w > page:
            x, y, row = 0, y + row, 0
        if y + h > page:
            pages, x, y, row = pages + 1, 0, 0, 0
        x, row = x + w, max(row, h)
    return pages


def cmd_pack(a):
    groups = {}
    for r in files_under(A.ART):
        im = Image.open(os.path.join(A.ART, r))
        m = A.bbox(np.asarray(im.convert("RGBA"))[..., 3] > 0)
        tight = (m[2] - m[0] + 1, m[3] - m[1] + 1) if m else im.size
        groups.setdefault(r.split("/")[0], []).append((im.size, tight))
    lines = ["# Sprite atlas plan (estimate)", "",
             "Tight-rect shelf packing, 2 px padding, 2048² pages. Unity SpriteAtlas assets are NOT generated here: "
             "creating and verifying them needs the Unity Editor (BLOCKED in this environment).", "",
             "| Group | Sprites | Full-rect MB (RGBA32) | Tight-rect MB | Pages @2048 | ASTC 6x6 MB (est.) |", "|---|---|---|---|---|---|"]
    for g, items in sorted(groups.items()):
        full = sum(w * h * 4 for (w, h), _ in items) / 1048576
        tight = sum(w * h * 4 for _, (w, h) in items) / 1048576
        pages = shelf_pack([t for _, t in items], 2048, 2)
        astc = pages * 2048 * 2048 * (128 / 36) / 8 / 1048576
        lines.append(f"| {g} | {len(items)} | {full:.1f} | {tight:.1f} | {pages} | {astc:.1f} |")
    os.makedirs(REPORTS, exist_ok=True)
    A.write_text(os.path.join(REPORTS, "atlas_plan.md"), "\n".join(lines) + "\n")
    log("pack -> Reports/ArtQuality/atlas_plan.md")
    return 0


# ---------------------------------------------------------------------------- diff / import / rollback

RENDER_TOLERANCE = (8 / 255.0, 0.001)   # Cycles CPU reruns differ by <=5/255 on ~0.02% of pixels (TEST_REPORT.md)


def same_render(p1, p2):
    if A.sha256(p1) == A.sha256(p2):
        return True
    a, _ = A.load_rgba(p1)
    b, _ = A.load_rgba(p2)
    if a.shape != b.shape:
        return False
    d = np.abs(a - b).max(-1)
    return float(d.max()) <= RENDER_TOLERANCE[0] and float((d > 0).mean()) <= RENDER_TOLERANCE[1]


def changed_files(stage_art):
    staged = set(files_under(stage_art))
    live = set(files_under(A.ART))
    changed = sorted(r for r in staged & live if not same_render(os.path.join(stage_art, r), os.path.join(A.ART, r)))
    return changed, sorted(staged - live), sorted(live - staged)


def side_by_side(rels, before_dir, after_dir, out, label):
    cell = 200
    sheet = Image.new("RGBA", (cell * 2 + 230, 30 + cell * len(rels)), (36, 38, 50, 255))
    d = ImageDraw.Draw(sheet)
    d.text((240, 8), "before", fill=(230, 230, 230))
    d.text((240 + cell, 8), "after", fill=(230, 230, 230))
    for i, r in enumerate(rels):
        y = 30 + i * cell
        d.text((6, y + cell // 2), r[:36], fill=(220, 220, 220))
        for j, base in enumerate((before_dir, after_dir)):
            p = os.path.join(base, r)
            if os.path.exists(p):
                im = Image.open(p).convert("RGBA")
                im.thumbnail((cell - 8, cell - 8), Image.LANCZOS)
                sheet.alpha_composite(im, (230 + j * cell + (cell - im.width) // 2, y + (cell - im.height) // 2))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    sheet.convert("RGB").save(out)
    return out


def cmd_diff(a):
    sp = stage_paths(a.stage)
    changed, added, removed = changed_files(sp["art"])
    lines = ["# Art diff (staging vs live)", "", f"- changed {len(changed)} · added {len(added)} · removed {len(removed)}", ""]
    if changed:
        lines += ["| Asset | Mean abs pixel Δ | Silhouette IoU |", "|---|---|---|"]
        for r in changed:
            x, _ = A.load_rgba(os.path.join(A.ART, r))
            y, _ = A.load_rgba(os.path.join(sp["art"], r))
            if x.shape == y.shape:
                lines.append(f"| {r} | {float(np.abs(x - y).mean()):.4f} | {A.iou(A.mask(x), A.mask(y)):.3f} |")
            else:
                lines.append(f"| {r} | size {x.shape[1]}x{x.shape[0]} → {y.shape[1]}x{y.shape[0]} | — |")
    lines += ["", "Added: " + (", ".join(added) or "none"), "", "Removed (not deleted by import): " + (", ".join(removed) or "none")]
    out = os.path.join(a.stage, "diff")
    os.makedirs(out, exist_ok=True)
    A.write_text(os.path.join(out, "diff.md"), "\n".join(lines) + "\n")
    for i in range(0, len(changed), 20):
        side_by_side(changed[i:i + 20], A.ART, sp["art"], os.path.join(out, f"before_after_{i // 20:02d}.png"), "diff")
    log(f"diff: {len(changed)} changed, {len(added)} added, {len(removed)} removed -> {os.path.relpath(out, A.ROOT)}")
    return 0


def cmd_import(a):
    sp = stage_paths(a.stage)
    vr = cmd_validate(argparse.Namespace(stage=a.stage, live=False))
    if vr:
        log("import ABORTED: staging has blocking validator issues (see " + os.path.relpath(os.path.join(a.stage, "report"), A.ROOT) + ")")
        return 1
    changed, added, _ = changed_files(sp["art"])
    targets = changed + added
    man = {m["path"] for m in A.load_json(sp["manifest"])}
    foreign = [r for r in targets if LIVE_REL + "/" + r not in man]
    if foreign:
        log("import ABORTED: files without generator provenance would be written: " + ", ".join(foreign[:5]))
        return 1
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    bdir = os.path.join(BACKUPS, stamp)
    journal = {"stamp": stamp, "pipeline": PIPELINE_VERSION, "replaced": changed, "added": added,
               "extra": ["Tools/AssetGen/import_settings.json", "Docs/ASSET_MANIFEST.json"], "complete": False}
    os.makedirs(bdir, exist_ok=True)
    for r in changed:
        os.makedirs(os.path.dirname(os.path.join(bdir, "Art", r)), exist_ok=True)
        shutil.copy2(os.path.join(A.ART, r), os.path.join(bdir, "Art", r))
        if os.path.exists(os.path.join(A.ART, r + ".meta")):
            shutil.copy2(os.path.join(A.ART, r + ".meta"), os.path.join(bdir, "Art", r + ".meta"))
    for e in journal["extra"]:
        os.makedirs(os.path.dirname(os.path.join(bdir, e)), exist_ok=True)
        shutil.copy2(os.path.join(A.ROOT, e), os.path.join(bdir, e))
    A.dump_json(journal, os.path.join(bdir, "journal.json"), indent=1)
    try:
        # Copy to temp names first, then atomically replace each file; any failure triggers a rollback.
        for r in targets:
            dst = os.path.join(A.ART, r)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(sp["art"], r), dst + ".aw_tmp")
        for r in targets:
            dst = os.path.join(A.ART, r)
            os.replace(dst + ".aw_tmp", dst)
        merged = A.load_json(A.SETTINGS)
        merged.update(A.load_json(sp["settings"]))
        A.dump_json(merged, A.SETTINGS, indent=1, sort_keys=True)
        live_man = {m["path"]: m for m in A.load_json(A.MANIFEST)}
        for m in A.load_json(sp["manifest"]):
            live_man[m["path"]] = m
        A.dump_json(list(live_man.values()), A.MANIFEST, indent=1)
        r = subprocess.run([sys.executable, os.path.join(A.ROOT, "Tools", "gen_meta.py"), "--refresh-textures"], capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError("gen_meta failed: " + r.stderr[-500:])
    except Exception as e:  # noqa: BLE001
        log("import FAILED (" + str(e) + "), rolling back")
        for r in targets:
            t = os.path.join(A.ART, r) + ".aw_tmp"
            if os.path.exists(t):
                os.remove(t)
        restore(bdir)
        return 2
    journal["complete"] = True
    A.dump_json(journal, os.path.join(bdir, "journal.json"), indent=1)
    write_lock()
    log(f"import: {len(changed)} replaced, {len(added)} added; backup {os.path.relpath(bdir, A.ROOT)}")
    return 0


def restore(bdir):
    j = A.load_json(os.path.join(bdir, "journal.json"))
    for r in j["replaced"]:
        shutil.copy2(os.path.join(bdir, "Art", r), os.path.join(A.ART, r))
        if os.path.exists(os.path.join(bdir, "Art", r + ".meta")):
            shutil.copy2(os.path.join(bdir, "Art", r + ".meta"), os.path.join(A.ART, r + ".meta"))
    for r in j["added"]:
        p = os.path.join(A.ART, r)
        if os.path.exists(p):
            os.remove(p)
            if os.path.exists(p + ".meta"):
                os.remove(p + ".meta")
    for e in j["extra"]:
        shutil.copy2(os.path.join(bdir, e), os.path.join(A.ROOT, e))
    log(f"restored {len(j['replaced'])} files, removed {len(j['added'])} added files from {os.path.relpath(bdir, A.ROOT)}")


def cmd_rollback(a):
    if a.journal:
        bdir = os.path.dirname(os.path.abspath(a.journal))
    else:
        dirs = sorted(glob.glob(os.path.join(BACKUPS, "*", "journal.json")))
        if not dirs:
            log("rollback: no import journal found")
            return 1
        bdir = os.path.dirname(dirs[-1])
    restore(bdir)
    write_lock()
    return 0


def write_lock():
    entries = []
    for r in files_under(A.ART):
        entries.append({"path": LIVE_REL + "/" + r, "sha256": A.sha256(os.path.join(A.ART, r))})
    gens = {}
    for g in sorted(glob.glob(os.path.join(A.ROOT, "Tools", "AssetGen", "art", "*.py")) + glob.glob(os.path.join(BLENDER_DIR, "*.py"))):
        gens[os.path.relpath(g, A.ROOT).replace("\\", "/")] = A.sha256(g)
    A.dump_json({"pipeline": PIPELINE_VERSION, "generators": gens, "outputs": entries}, LOCK, indent=1)
    log(f"lock: {len(entries)} outputs, {len(gens)} generator scripts -> {os.path.relpath(LOCK, A.ROOT)}")


def cmd_lock(a):
    write_lock()
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("generate", "render", "validate", "preview", "pack", "diff", "import", "rollback", "lock"):
        sp = sub.add_parser(name)
        sp.add_argument("--stage", default=DEFAULT_STAGE)
        if name == "generate":
            sp.add_argument("--with-blender", action="store_true")
            sp.add_argument("--only", default=None)
        if name == "render":
            sp.add_argument("--only", default=None)
        if name == "validate":
            sp.add_argument("--live", action="store_true")
        if name == "preview":
            sp.add_argument("--assets", default="Heroes/*_idle.png")
            sp.add_argument("--name", default="heroes")
            sp.add_argument("--out", default=None)
            sp.add_argument("--stage-preview", action="store_true")
        if name == "rollback":
            sp.add_argument("--journal", default=None)
    a = p.parse_args(argv)
    a.stage = os.path.abspath(a.stage)
